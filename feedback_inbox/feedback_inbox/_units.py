"""Keep the path units' watch lists equal to the games that exist.

systemd ``.path`` units take no globs, so each ``*_binaries`` folder is listed
in a generated drop-in. The set changes only when a game is added or removed;
the drop-in is rewritten, and systemd reloaded, only then (a reload per tick
would be the daemon-reload loop the fleet rules forbid).
"""

from __future__ import annotations

import subprocess
from typing import TYPE_CHECKING

from feedback_inbox._bundle import binaries_dirs, feedback_dirs

if TYPE_CHECKING:
    from collections.abc import Callable, Sequence
    from pathlib import Path

WATCH_PATH = "feedback-inbox.path"
SYNC_PATH = "feedback-inbox-sync.path"
SYSTEMCTL = "/usr/bin/systemctl"
_HEADER = "# Generated by `feedback-inbox sync`; do not edit.\n[Path]\n"


def _dropin(unit_dir: Path, unit: str) -> Path:
    return unit_dir / f"{unit}.d" / "dirs.conf"


def _render(folders: list[Path]) -> str:
    return _HEADER + "".join(f"PathChanged={d}\n" for d in folders)


def desired(data_root: Path, unit_dir: Path) -> dict[Path, str]:
    """The drop-ins that should exist: feedback folders, and game folders."""
    return {
        _dropin(unit_dir, WATCH_PATH): _render(feedback_dirs(data_root)),
        _dropin(unit_dir, SYNC_PATH): _render(binaries_dirs(data_root)),
    }


def run_systemctl(args: Sequence[str]) -> int:
    """Run ``systemctl --user <args>`` and return its exit code."""
    return subprocess.run([SYSTEMCTL, "--user", *args], check=False).returncode


def sync_units(
    data_root: Path,
    unit_dir: Path,
    systemctl: Callable[[Sequence[str]], int],
) -> bool:
    """Rewrite drifted drop-ins, then reload and re-arm once; True if changed."""
    changed = False
    for path, text in desired(data_root, unit_dir).items():
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        changed = True
    if not changed:
        return False
    for args in (["daemon-reload"], ["restart", WATCH_PATH, SYNC_PATH]):
        if systemctl(args):
            msg = f"systemctl --user {' '.join(args)} failed"
            raise RuntimeError(msg)
    return True
